#!/usr/bin/env python3
"""patch-dwm.py - extra checked edits to dwm.c / config.h (called by patch-dwm.sh).

  1. gaps:   replaces tile() and monocle() with gap-aware versions and makes sure
             config.h defines `gappx` (8 px around and between tiled windows).
  2. power button: draws it in the normal bar colors (no accent-colored box).
  3. power icon:   shrinks the padded "  <icon>  " in config.h to just the icon.
  4. live key:     adds Super+Ctrl+Shift+W (dwm-live pick) to an existing config.h.
  5. empty-workspace animation: view() starts the dwm-flash ripple when the
             workspace you switch to has no windows.
  6. bar layout: updatebarpos() and createmon() read barcfg.h (written by dwm-bar), so the
             dwm bar can float, sit on top or bottom, or be shown next to polybar; config.h
             gets `#include "barcfg.h"`, its tags come from dwm-bar and gappx from BAR_GAP.
  7. bar key:  adds Super+Shift+B (dwm-bar) to an existing config.h.
  8. settings key: adds Super+Shift+D (dwm-settings) to an existing config.h.
  9. status clicks: a left click on the status text runs dwm-status-click with the index of the
             clicked character (wifi, Bluetooth, sound, battery profiles); adds the
             ClkStatusSegment enum, prototype and dispatch that config.h's binding needs.

Every edit looks for exact text first and says so if it is not found; nothing is
guessed. Files are backed up once as <file>.bak-le-dwm before the first change.
Safe to run repeatedly.

Usage: patch-dwm.py [path/to/dwm-source]   (default: ~/dwm)
"""
import os
import re
import shutil
import sys

SRC = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/dwm")
DWMC = os.path.join(SRC, "dwm.c")
CONFH = os.path.join(SRC, "config.h")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, text):
    bak = path + ".bak-le-dwm"
    if not os.path.exists(bak):
        shutil.copy2(path, bak)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


GAP_MARK = "/* le-dwm-config: gaps */"
GAP_MARK2 = "/* le-dwm-config: gaps v2 */"
BAR_MARK = "/* le-dwm-config: bar layout */"
BARCFG = os.path.join(SRC, "barcfg.h")

TILE_TEMPLATE = r"""@MARK@
void
tile(Monitor *m)
{
	unsigned int i, n, nm;
	int g = gappx, og = @OG@, aw, mw, sw, sx = 0, my, ty, h;
	Client *c;

	for (n = 0, c = nexttiled(m->clients); c; c = nexttiled(c->next), n++);
	if (n == 0)
		return;

	nm = MIN(n, m->nmaster);
	aw = m->ww - 2 * og;                   /* width inside the outer gaps */
	if (nm && n > nm) {                    /* master column + stack column */
		mw = (int)((aw - g) * m->mfact);
		sw = aw - g - mw;
		sx = m->wx + og + mw + g;
	} else if (nm) {                       /* only master windows */
		mw = aw;
		sw = 0;
	} else {                               /* nmaster == 0: everything in the stack */
		mw = 0;
		sw = aw;
		sx = m->wx + og;
	}
	for (i = 0, my = ty = g, c = nexttiled(m->clients); c; c = nexttiled(c->next), i++)
		if (i < nm) {
			h = (m->wh - my - g - (int)(nm - i - 1) * g) / (int)(nm - i);
			resize(c, m->wx + og, m->wy + my, mw - 2 * c->bw, h - 2 * c->bw, 0);
			if (my + HEIGHT(c) + g < m->wh)
				my += HEIGHT(c) + g;
		} else {
			h = (m->wh - ty - g - (int)(n - i - 1) * g) / (int)(n - i);
			resize(c, sx, m->wy + ty, sw - 2 * c->bw, h - 2 * c->bw, 0);
			if (ty + HEIGHT(c) + g < m->wh)
				ty += HEIGHT(c) + g;
		}
}
"""

MONOCLE_STOCK = "resize(c, m->wx, m->wy, m->ww - 2 * c->bw, m->wh - 2 * c->bw, 0);"
MONOCLE_V1 = ("resize(c, m->wx + gappx, m->wy + gappx, "
              "m->ww - 2 * c->bw - 2 * gappx, m->wh - 2 * c->bw - 2 * gappx, 0);")
MONOCLE_V2 = ("resize(c, m->wx + BAR_OG, m->wy + gappx, "
              "m->ww - 2 * c->bw - 2 * BAR_OG, m->wh - 2 * c->bw - 2 * gappx, 0);")

FALLBACK_BARCFG = """/* generated by dwm-bar: do not edit, run `dwm-bar` instead */
#define BAR_GAP 8
/* horizontal gap left outside the tiled windows (the bars' own side margin already provides part of it) */
#define BAR_OG (gappx > bar_side ? gappx - bar_side : 0)
static const int bar_dwm_show      = 1;
static const int bar_dwm_top       = 1;
static const int bar_side          = 8;   /* side margin of the floating bars */
static const int bar_vgap          = 8;   /* gap between the dwm bar and the screen edge */
static const int bar_reserve_top   = 0;   /* room kept for the second bar (polybar) */
static const int bar_reserve_bottom = 38;
"""

NEW_UPDATEBARPOS = BAR_MARK + r"""
void
updatebarpos(Monitor *m)
{
	/* work area = screen minus the side margin of floating bars and the room kept for polybar */
	m->wx = m->mx + bar_side;
	m->ww = m->mw - 2 * bar_side;
	m->wy = m->my + bar_reserve_top;
	m->wh = m->mh - bar_reserve_top - bar_reserve_bottom;
	if (m->showbar) {
		m->wh -= bh + bar_vgap;
		if (m->topbar) {
			m->by = m->wy + bar_vgap;
			m->wy += bh + bar_vgap;
		} else
			m->by = m->wy + m->wh;
	} else
		m->by = -bh;
}
"""


def ensure_gappx(bars_ok=False):
    """Make sure config.h defines gappx. Returns True if it does."""
    cfg = read(CONFH)
    if re.search(r"\bgappx\b", cfg):
        return True
    val = "BAR_GAP" if bars_ok else "8"
    line = ("static const int gappx              = %s;        "
            "/* gap around and between tiled windows */\n" % val)
    for anchor in (r"^static const int bottompad.*\n", r"^static const unsigned int borderpx.*\n"):
        m = re.search(anchor, cfg, re.M)
        if m:
            write(CONFH, cfg[:m.end()] + line + cfg[m.end():])
            print("patch-dwm: added gappx = %s to config.h" % val)
            return True
    print("patch-dwm: could not place 'gappx' in config.h; add\n"
          "           static const int gappx = 8;\n"
          "           near the top of it, then run patch-dwm.sh again.", file=sys.stderr)
    return False


def patch_bars():
    """Bar layout: updatebarpos()/createmon() read barcfg.h. Returns True when dwm.c has it."""
    src = read(DWMC)
    if BAR_MARK not in src:
        pat = re.compile(r"\nvoid\nupdatebarpos\(Monitor \*m\)\n\{.*?\n\}\n", re.S)
        mt = pat.search(src)
        if (not mt or "m->showbar" not in mt.group(0) or "m->by" not in mt.group(0)
                or src.count("m->showbar = showbar;") != 1 or src.count("m->topbar = topbar;") != 1):
            print("patch-dwm: updatebarpos()/createmon() differ from what I expect; the bar layout "
                  "(floating, top/bottom, single bar) is not available", file=sys.stderr)
            return False
        src = (src[:mt.start()] + "\n" + NEW_UPDATEBARPOS + src[mt.end():])
        src = src.replace("m->showbar = showbar;", "m->showbar = bar_dwm_show;")
        src = src.replace("m->topbar = topbar;", "m->topbar = bar_dwm_top;")
        needs_write = True
    else:
        needs_write = False
    if not os.path.exists(BARCFG):
        with open(BARCFG, "w", encoding="utf-8") as f:
            f.write(FALLBACK_BARCFG)
        print("patch-dwm: wrote a default barcfg.h (dwm-bar regenerates it)")
    cfg = read(CONFH)
    if '#include "barcfg.h"' not in cfg:
        m = re.search(r"^static const unsigned int borderpx.*\n", cfg, re.M)
        inc = '#include "barcfg.h"   /* generated by dwm-bar: bar layout, gaps, tag style */\n'
        if m:
            cfg = cfg[:m.start()] + inc + cfg[m.start():]
        else:
            nl = cfg.find("\n") + 1
            cfg = cfg[:nl] + inc + cfg[nl:]
        write(CONFH, cfg)
        print('patch-dwm: config.h now includes barcfg.h')
    if needs_write:
        write(DWMC, src)
        print("patch-dwm: bar layout applied")
    else:
        print("patch-dwm: bar layout already applied")
    return True


def patch_gaps(bars_ok):
    src = read(DWMC)
    mark = GAP_MARK2 if bars_ok else GAP_MARK
    og = "(gappx > bar_side ? gappx - bar_side : 0)" if bars_ok else "gappx"
    og = "BAR_OG" if bars_ok else "gappx"
    monocle_new = MONOCLE_V2 if bars_ok else MONOCLE_V1
    have_old = GAP_MARK in src or GAP_MARK2 in src
    if mark in src and monocle_new in src:
        ensure_gappx(bars_ok)   # dwm.c needs gappx even when config.h was restored from a backup
        print("patch-dwm: gaps already applied")
        return
    if not have_old and "gappx" in src:
        print("patch-dwm: dwm.c already mentions gappx (another gaps patch?); skipping gaps", file=sys.stderr)
        return
    if not ensure_gappx(bars_ok):
        return
    pat = re.compile(r"(?:/\* le-dwm-config: gaps[^\n]*\*/\n)?void\ntile\(Monitor \*m\)\n\{.*?\n\}\n", re.S)
    mt = pat.search(src)
    if not mt or "m->nmaster" not in mt.group(0):
        print("patch-dwm: could not find tile() in dwm.c; skipping gaps", file=sys.stderr)
        return
    tile = TILE_TEMPLATE.replace("@MARK@", mark).replace("@OG@", og)
    src = src[:mt.start()] + tile + src[mt.end():]
    for old in (MONOCLE_STOCK, MONOCLE_V1, MONOCLE_V2):
        if old != monocle_new and src.count(old) == 1:
            src = src.replace(old, monocle_new)
            break
    else:
        if monocle_new not in src:
            print("patch-dwm: monocle() line not found; tiled gaps applied, monocle left as is",
                  file=sys.stderr)
    write(DWMC, src)
    print("patch-dwm: gaps applied")


def patch_tags_and_gap():
    """config.h: tags come from barcfg.h when dwm-bar picks a set; gappx follows BAR_GAP."""
    cfg = read(CONFH)
    if '#include "barcfg.h"' not in cfg:
        return
    new = cfg
    if "BAR_TAGS" not in new:
        m = re.search(r"^static const char \*tags\[\]\s*=\s*(\{.*?\});[ \t]*\n", new, re.M | re.S)
        if m:
            repl = ("#ifdef BAR_TAGS\n"
                    "static const char *tags[] = BAR_TAGS;   /* chosen with dwm-bar */\n"
                    "#else\n"
                    "static const char *tags[] = %s;\n"
                    "#endif\n" % m.group(1))
            new = new[:m.start()] + repl + new[m.end():]
        else:
            print("patch-dwm: tags[] not found in config.h; dwm-bar cannot change the tag style",
                  file=sys.stderr)
    new2 = re.sub(r"(static const int gappx\s*=\s*)\d+;", r"\1BAR_GAP;", new, count=1)
    if new2 != new:
        new = new2
    if new != cfg:
        write(CONFH, new)
        print("patch-dwm: config.h tags/gaps now follow dwm-bar")


